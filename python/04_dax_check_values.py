"""
Phase 6 helper: compute, in pandas, the numbers each DAX measure in dax/measures.md should show.
Build the measures in Power BI, put them in a card or table, and compare against this output.
Writes reports/dax_check_values.md.
"""
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
PROC = ROOT / "data" / "processed"

cust = pd.read_csv(PROC / "engineered.csv")
scores = pd.read_csv(PROC / "customer_scores.csv")
# Same 1:1 relationship as the Power BI model (id <-> id)
df = cust.merge(scores, on="id", how="left", validate="one_to_one")
assert len(df) == len(cust) and df["tier"].notna().all()
test = df[df["split"] == "test"]

TIERS = ["High", "Medium", "Low"]
lines = ["# DAX check values", "",
         "Generated by `python/04_dax_check_values.py`. Each number is what the matching measure in "
         "`dax/measures.md` should show in Power BI.", ""]

# --- whole dataset, no slicers
base_test = test["Response"].mean()
lines += ["## No filters (card visuals)", "", "| Measure | Expected |", "|---|---|",
          f"| Customers | {len(df):,} |",
          f"| Responders | {int(df['Response'].sum()):,} |",
          f"| Response Rate | {df['Response'].mean():.2%} |",
          f"| Test Customers | {len(test):,} |",
          f"| Test Response Rate | {base_test:.2%} |",
          f"| Expected Responders | {df['probability'].sum():,.0f} |",
          f"| Avg Propensity | {df['probability'].mean():.2%} |",
          f"| High Tier Customers | {(df['tier'] == 'High').sum():,} |", ""]

# --- by tier (rows = customer_scores[tier])
lines += ["## Table visual with customer_scores[tier] on rows", "",
          "| tier | Customers | Share of Customers | Test Response Rate | Baseline Response Rate | Lift vs Random | Share of Responders Captured | Avg Propensity (Test) |",
          "|---|---|---|---|---|---|---|---|"]
for t in TIERS:
    d, dt = df[df["tier"] == t], test[test["tier"] == t]
    rate = dt["Response"].mean()
    lines.append(f"| {t} | {len(d):,} | {len(d) / len(df):.1%} | {rate:.2%} | {base_test:.2%} | "
                 f"{rate / base_test:.2f} | {dt['Response'].sum() / test['Response'].sum():.1%} | "
                 f"{dt['probability'].mean():.2%} |")
lines.append("")

# --- High tier lift within each zone: the baseline changes with the zone slice
lines += ["## Matrix: zone on rows, slicer tier = High (shows that the baseline follows the zone)", "",
          "| zone | High Tier Customers | Test Response Rate (High) | Baseline Response Rate (zone) | Lift vs Random | Expected Responders (High) |",
          "|---|---|---|---|---|---|"]
for z, dz in df.groupby("zone"):
    tz = test[test["zone"] == z]
    hi_rate = tz.loc[tz["tier"] == "High", "Response"].mean()
    base = tz["Response"].mean()
    lines.append(f"| {z} | {(dz['tier'] == 'High').sum():,} | {hi_rate:.2%} | {base:.2%} | "
                 f"{hi_rate / base:.2f} | {dz.loc[dz['tier'] == 'High', 'probability'].sum():,.0f} |")
lines.append("")

# --- opportunity by channel group
lines += ["## Bar chart: Channel Group, High Tier Customers (sorted)", "",
          "| Channel Group | High Tier Customers | Expected Responders (High) |", "|---|---|---|"]
ch = (df[df["tier"] == "High"].groupby("Channel Group")
      .agg(n=("id", "size"), exp=("probability", "sum")).sort_values("n", ascending=False))
for g, r in ch.iterrows():
    lines.append(f"| {g} | {int(r['n']):,} | {r['exp']:,.0f} |")
lines.append("")

out = ROOT / "reports" / "dax_check_values.md"
out.write_text("\n".join(lines), encoding="utf-8")
print("\n".join(lines))
